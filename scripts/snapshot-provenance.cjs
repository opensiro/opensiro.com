'use strict';

// Machine-readable materialized-snapshot provenance. The Index source SHA is
// read from the generated canonical-source marker, never inferred from a website
// commit, an upstream harness pin, or a previously published snapshot.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const manifestPath = path.join(root, 'assets/harness-index/source-manifest.json');
const template = fs.readFileSync(path.join(root, 'scripts/templates/vsm-index-source.html'), 'utf8');
const marker = template.match(/<!-- VSM INDEX SOURCE: opensiro\/vsm-harness-index@([0-9a-f]{40}); generated by scripts\/sync-vsm-index\.cjs -->/);
if (!marker) throw new Error('Canonical template is missing a full Index commit SHA');
const indexSha = marker[1];

const context = {window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'assets/harness-index/manifest.js'), 'utf8'), context);
const snapshot = context.window.harnessSnapshot;
if (!snapshot || !Array.isArray(snapshot.entries) || !/^[a-f0-9]{16}$/.test(snapshot.revision)) {
  throw new Error('Invalid generated harness snapshot');
}
const expected = {
  source_repository: 'opensiro/vsm-harness-index',
  source_branch: 'main',
  source_sha: indexSha,
  source_url: 'https://github.com/opensiro/vsm-harness-index/tree/' + indexSha,
  snapshot_revision: snapshot.revision,
  source_updated_at: snapshot.updatedAt,
  included_assessments: snapshot.entries.length,
  all_rows_file: snapshot.fullFile
};
const serialized = JSON.stringify(expected, null, 2) + '\n';

if (process.argv.includes('--print-source-sha')) {
  // A missing manifest is the unsynchronized state, not a match.
  try {
    const current = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    process.stdout.write(typeof current.source_sha === 'string' ? current.source_sha : '');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
} else if (process.argv.includes('--check')) {
  if (fs.readFileSync(manifestPath, 'utf8') !== serialized) {
    throw new Error('Snapshot provenance is stale or inconsistent with materialized output');
  }
  console.log('Source manifest validated for Index ' + indexSha);
} else {
  if (process.argv.includes('--source-sha')) {
    const value = process.argv[process.argv.indexOf('--source-sha') + 1];
    if (value !== indexSha) throw new Error('Checked out Index SHA and generated Index SHA disagree');
  }
  if (!fs.existsSync(manifestPath) || fs.readFileSync(manifestPath, 'utf8') !== serialized) {
    fs.writeFileSync(manifestPath, serialized);
  }
  console.log('Materialized snapshot provenance: Index ' + indexSha);
}
